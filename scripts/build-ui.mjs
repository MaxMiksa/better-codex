// These checked-in bundles let source installs and portable packages run without pnpm.
import {access, mkdir, writeFile} from 'node:fs/promises';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import registry from '../src/runtime/feature-registry.cjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const banner='/* Generated by scripts/build-ui.mjs; edit the source in src/features/. */';
const options={
  absWorkingDir:root, bundle:true, target:'es2022', loader:{'.css':'text'},
  charset:'utf8', write:false, banner:{js:banner},
};

async function entryFor(stem){
  const [feature,name]=stem.split('/');
  const base=`src/features/${feature}/ui/${name}`;
  try{
    await access(join(root,base+'.ts'));
    return base+'.ts';
  }catch(error){
    if(error.code!=='ENOENT')throw error;
    return base+'.js';
  }
}

async function compile(feature){
  const entry=await entryFor(feature.entry);
  let browserContents;
  if(feature.key==='accent'){
    // Preserve the boolean return value observed by idempotent-install checks.
    const built=await build({...options,banner:undefined,entryPoints:[entry],platform:'browser',format:'iife',globalName:'__bcAccent'});
    const code=`${banner}\n(() => {\n${built.outputFiles[0].text}return __bcAccent.default();\n})();\n`;
    browserContents=Buffer.from(code,'utf8');
  }else{
    const built=await build({...options,entryPoints:[entry],platform:'browser',format:'iife'});
    browserContents=built.outputFiles[0].contents;
  }
  const outputs=[[`ui/${feature.file}.js`,browserContents]];
  if(feature.hostFile){
    const catalogEntry='src/features/command-menu/shared/command-catalog.ts';
    const built=await build({...options,banner:undefined,entryPoints:[catalogEntry],platform:'node',format:'cjs'});
    const cjs=`${banner}\n${built.outputFiles[0].text}\nmodule.exports=module.exports.default||module.exports;\n`;
    outputs.push([`host/${feature.hostFile}`,Buffer.from(cjs,'utf8')]);
  }
  return outputs;
}

const outputs=(await Promise.all(registry.features.map(compile))).flat();
for(const [file,contents] of outputs){
  const dest=join(root,'src/generated',file);
  await mkdir(dirname(dest),{recursive:true});
  await writeFile(dest,contents);
}
