// Build the offline bundles from pinned public sources. No installed Codex
// asset is read. Only the custom-element name is changed, so ours cannot
// register or replace the tag used by Codex's own viewer.
import {readFile, realpath, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';

const here = new URL('./', import.meta.url);
const at = path => fileURLToPath(new URL(path, here));
const ui = new URL('../../src/features/workspace-tree/ui/', here);
const preview = new URL('../../src/features/workspace-tree/host/preview/', here);
const tag = 'bc-workspace-file-tree';

async function packageDir(name, require) {
  for (const lookup of require.resolve.paths(name)) {
    try {
      return await realpath(join(lookup, name));
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  throw new Error('Missing build dependency: ' + name);
}

const requireHere = createRequire(import.meta.url);
const trees = await packageDir('@pierre/trees', requireHere);
// Resolve transitive notices from the pinned Trees package, not from a
// coincidentally hoisted dependency at the workspace root.
const requireTrees = createRequire(join(trees, 'package.json'));
const packages = [
  ['@pierre/trees', ['LICENSE.md', 'NOTICE.md']],
  ['@pierre/theming', ['LICENSE.md']],
  ['preact', ['LICENSE']],
  ['preact-render-to-string', ['LICENSE']],
];
const notices = [];
for (const [name, files] of packages) {
  const dir = name === '@pierre/trees' ? trees : await packageDir(name, requireTrees);
  const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  notices.push(name+' '+pkg.version);
  for (const file of files) notices.push((await readFile(join(dir, file), 'utf8')).trim());
}
const isolation = new Map([
  ['constants.js', [['"file-tree-container"', '"'+tag+'"']]],
  ['web-components.js', [['customElements.get("file-tree-container")', 'customElements.get("'+tag+'")']]],
  ['FileTree.js', [
    ['document.createElement("file-tree-container")', 'document.createElement("'+tag+'")'],
    ['<file-tree-container id=', '<'+tag+' id='],
    ['</file-tree-container>', '</'+tag+'>'],
  ]],
]);
const changed = new Set();
const result = await build({
  absWorkingDir: at('./'),
  stdin: {contents:"export {FileTree} from '@pierre/trees';", resolveDir:at('./'), sourcefile:'workspace-tree-renderer.js'},
  bundle: true,
  minify: true,
  platform: 'browser',
  format: 'iife',
  globalName: 'bcTreeRenderer',
  target: 'chrome120',
  legalComments: 'inline',
  write: false,
  banner: {js:'/* Generated by scripts/workspace-tree/build.mjs; upstream notices in TREE-RENDERER-LICENSES.txt. */'},
  plugins: [{
    name:'isolate-workspace-tree-element',
    setup({onLoad}) {
      onLoad({filter:/(?:constants|web-components|FileTree)\.js$/}, async ({path}) => {
        const file = path.split(/[/\\]/).at(-1);
        if (!/[@]pierre[/\\]trees[/\\]dist[/\\]/.test(path) || !isolation.has(file)) return;
        let code = await readFile(path, 'utf8');
        for (const [needle, replacement] of isolation.get(file)) {
          if (!code.includes(needle)) throw new Error('Review workspace-tree element contract: '+file);
          code = code.replace(needle, replacement);
        }
        changed.add(file);
        return {contents:code, loader:'js'};
      });
    },
  }],
});
if (changed.size !== isolation.size || result.outputFiles.length !== 1) throw new Error('Workspace-tree element isolation was not applied');
await writeFile(new URL('tree-renderer.js',ui),result.outputFiles[0].contents);
await writeFile(new URL('TREE-RENDERER-LICENSES.txt',ui),notices.join('\n\n')+'\n');

const parserNotices = [];
for (const [name, license] of [['jsonc-parser', 'LICENSE.md'], ['yaml', 'LICENSE'], ['smol-toml', 'LICENSE']]) {
  const dir = await packageDir(name, requireHere);
  const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  parserNotices.push(name+' '+pkg.version, (await readFile(join(dir, license), 'utf8')).trim());
}
const configBundle = await build({
  absWorkingDir: at('./'),
  stdin: {
    contents: [
      "export {parseTree as parseJsonc} from 'jsonc-parser';",
      "export {parseAllDocuments as parseYaml} from 'yaml';",
      "export {parse as parseToml} from 'smol-toml';",
    ].join('\n'),
    resolveDir: at('./'), sourcefile: 'config-parsers.js',
  },
  bundle: true,
  minify: true,
  platform: 'node',
  mainFields: ['module', 'main'],
  format: 'cjs',
  target: 'node24',
  legalComments: 'inline',
  write: false,
  banner: {js:'/* Generated by scripts/workspace-tree/build.mjs; upstream notices in CONFIG-PARSER-LICENSES.txt. */'},
});
await writeFile(new URL('config-parsers.cjs',preview),configBundle.outputFiles[0].contents);
await writeFile(new URL('CONFIG-PARSER-LICENSES.txt',preview),parserNotices.join('\n\n')+'\n');
